/** One digit system in interface text: Urdu-Indic digits (۰-۹) in room names and captions are shown as 0-9, like
 *  every other number on the screen. (The ayah-end marker inside the Qur'an text keeps its Arabic digits.) */
const URDU_DIGITS = "۰۱۲۳۴۵۶۷۸۹";
export const plainDigits = (text) => String(text ?? "").replace(/[۰-۹]/g, (d) => String(URDU_DIGITS.indexOf(d)));

export const LANG_CODES = Object.keys(STRINGS);
let current = "en";

export const lang = () => current;
export const t = (key) => STRINGS[current][key] ?? STRINGS.en[key] ?? key;
/** A string in a given language, for screens shown before the player's language is known (loading, load error). */
export const tFor = (code, key) => STRINGS[code]?.[key] ?? STRINGS.en[key] ?? key;
export const keys = (code) => Object.keys(STRINGS[code]);

/** Pick the interface language: the player's choice, else the host language (Urdu if it starts with "ur"). */
export function resolveLang(setting, hostLang) {
  if (setting === "en" || setting === "ur") return setting;
  return /^ur\b/i.test(hostLang ?? "") ? "ur" : "en";
}

/** Switch language: flips direction, refreshes every [data-t] label and every caption already on screen. */
export function applyLang(code) {
  current = STRINGS[code] ? code : "en";
  if (typeof document === "undefined") return;
  const root = document.documentElement;
  root.lang = current;
  root.dir = current === "ur" ? "rtl" : "ltr";
  document.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t(el.dataset.t); });
  document.querySelectorAll("[data-t-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.tAria)));
  document.querySelectorAll("[data-en]").forEach((el) => {
    el.textContent = plainDigits(el.dataset[current] ?? el.dataset.en);
    el.lang = current;
  });
}
